#!/usr/bin/env python3
"""Builds qml/aion2/schedule.js (the Schedule's fixed times and field bosses)
from A2 Tools' Event Timers plugin (GPL-3.0, taengu/A2Tools-Plugins,
plugins/event-timers/schedule.js, made there from the game's own tables:
EventSchedule, FieldEvent, PeriodSpawn, RiftData), English names only.

    python3 tools/aion2-schedule-import.py <A2Tools-Plugins checkout>
"""
import json
import pathlib
import re
import subprocess
import sys

src = pathlib.Path(sys.argv[1])
text = (src / "plugins/event-timers/schedule.js").read_text()
revision = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()


def const(name):
    start = text.index(f"const {name} = ") + len(f"const {name} = ")
    value, _ = json.JSONDecoder().raw_decode(text[start:])
    return value


events = const("EVENTS")
bosses = const("FIELD_BOSSES")
words = const("EVENT_TEXT")


def en(key):
    w = words.get(key)
    if not w:
        raise SystemExit(f"no English name for {key}")
    # The game's tags (<...>) and doubled spaces out.
    return re.sub(r"\s+", " ", re.sub(r"<[^>]*>", "", w.get("en") or next(iter(w.values())))).strip()


out_events = []
for e in events:
    names = [en(e["name"])] + [en(a) for a in e.get("also", [])]
    entry = {
        "id": e["id"],
        "kind": e["kind"],
        "name": " · ".join(names) if e["kind"] == "boss" else names[0],
        "where": [en(w) for w in e["where"]],
        "side": e["side"],
        "days": e["days"],
        "starts": e["starts"],
        "minutes": e["minutes"],
    }
    if e.get("utc"):
        entry["utc"] = True
    out_events.append(entry)

out_bosses = {
    bid: {"name": en(b["name"]), "where": en(b["where"]), "side": b["side"], "level": b["level"]}
    for bid, b in sorted(bosses.items())
}

dest = pathlib.Path(__file__).resolve().parent.parent / "qml/aion2/schedule.js"
dest.write_text(
    ".pragma library\n"
    "// The Schedule's fixed times and the field bosses that respawn after a\n"
    "// kill, from A2 Tools' Event Timers plugin (GPL-3.0,\n"
    f"// https://github.com/taengu/A2Tools-Plugins, revision {revision}),\n"
    "// made there from the game's own tables. Generated by\n"
    "// tools/aion2-schedule-import.py: don't edit by hand.\n"
    "// starts: minutes after midnight, server time (UTC with utc: true);\n"
    "// days: 0 = Sunday; minutes: how long it runs, 0 if the tables don't say.\n"
    f"var EVENTS = {json.dumps(out_events, ensure_ascii=False)}\n"
    f"var FIELD_BOSSES = {json.dumps(out_bosses, ensure_ascii=False)}\n"
)
print(f"{dest}: {len(out_events)} events, {len(out_bosses)} field bosses")
