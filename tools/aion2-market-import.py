#!/usr/bin/env python3
"""Takes the Market plugin over from the Clicktrough plugins (same author,
GPL-3.0): its tables (recipes, names, NPC prices, the item list) and its
logic (anomaly.js, calc.js) as one QML JavaScript library,
qml/aion2/marketkit.js, and its notice into crates/aion2/data/market/.

    tools/aion2-market-import.py <A2Tools-Clicktrough-Plugins>/plugins/market

The plugin's scripts are kept as they are; only `globalThis` becomes the
library's own object `G` (QML's global object is read only). The page
itself (plugin.js) is qml/aion2/MarketPanel.qml.
"""
import re
import shutil
import sys
from pathlib import Path

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
out_js = root / "qml" / "aion2" / "marketkit.js"
out_data = root / "crates" / "aion2" / "data" / "market"

parts = [
    ".pragma library\n",
    "// Generated by tools/aion2-market-import.py from the Clicktrough Market plugin\n",
    "// (data.js, items.js, anomaly.js, calc.js; GPL-3.0, the data's notice in\n",
    "// crates/aion2/data/market/). Do not edit by hand.\n",
    "var G = {};\n",
    "G.grouped = function (v) { var n = Math.round(v), t = String(Math.abs(n)), o = '';\n",
    "  while (t.length > 3) { o = ',' + t.slice(-3) + o; t = t.slice(0, -3); }\n",
    "  return (n < 0 ? '-' : '') + t + o; };\n",
]
for name in ["data.js", "items.js", "anomaly.js", "calc.js"]:
    text = (src / name).read_text(encoding="utf-8")
    parts.append(f"// ---- {name} ----\n")
    if name in ("anomaly.js", "calc.js"):
        # Numeric separators (50_000) are newer than Qt 6.4's JavaScript.
        text = re.sub(r"(?<![\w$.])\d+(?:_\d+)+\b", lambda m: m.group(0).replace("_", ""), text)
        # QML's Number.toLocaleString takes a Qt locale and ignores "en-US":
        # thousands with commas, as in the browser.
        text = re.sub(r'Math\.round\(([^()]*(?:\([^()]*\))?)\)\.toLocaleString\("en-US"\)', r'G.grouped(\1)', text)
    parts.append(text.replace("globalThis.", "G."))
    parts.append("\n")
parts.append("var D = G.MARKET_DATA;\nvar C = G.MarketCalc;\nvar A = G.MarketAnomaly;\n")
text = "".join(parts)
left = [line[:120] for line in text.split("\n")
        if re.search(r"\|\|=|\?\?=|&&=|\{\s*\.\.\.|\.flat\(|flatMap|fromEntries|(?<![\w$.])\d+_\d|toLocaleString\(", line)
        and not line.lstrip().startswith("//")]
if left:
    sys.exit("not readable by Qt 6.4's JavaScript:\n" + "\n".join(left[:10]))
out_js.write_text(text, encoding="utf-8")

out_data.mkdir(parents=True, exist_ok=True)
for notice in sorted(src.glob("NOTICE-*.txt")):
    shutil.copy(notice, out_data / notice.name)
shutil.copy(src / "README.md", out_data / "README-plugin.md")
print(f"{out_js} ({out_js.stat().st_size // 1024} KB), {out_data}")
