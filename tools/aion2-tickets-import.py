#!/usr/bin/env python3
"""Takes the game's content tickets (keys, entry and reward counts, usage
times: name, highest count, server-wide or not, reset) from the Clicktrough
Inventory plugin's data.js (read there from SkeeveAN's Aion-DPS-Meter, MIT,
from the game client) into qml/aion2/chartickets.js for the Characters area.

    tools/aion2-tickets-import.py <A2Tools-Clicktrough-Plugins>/plugins/inventory
"""
import json
import re
import shutil
import sys
from pathlib import Path

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
text = (src / "data.js").read_text(encoding="utf-8")
# One object after "globalThis.INVENTORY_DATA = ", the tickets one of its keys.
m = re.search(r"INVENTORY_DATA\s*=\s*", text)
if not m:
    sys.exit("no INVENTORY_DATA in data.js")
data, _ = json.JSONDecoder().raw_decode(text[m.end():])
tickets = data.get("tickets")
if not isinstance(tickets, dict) or not tickets:
    sys.exit("no tickets in data.js")
out = {}
for tid, t in sorted(tickets.items(), key=lambda kv: int(kv[0])):
    full, short, top, sub_top, per_server, is_time, reset = t
    # Unnamed usage times (the game's generic "Usage Time") say nothing.
    if is_time and short == "Usage Time":
        continue
    out[tid] = [short, top, sub_top, bool(per_server), bool(is_time), reset]
js = (
    ".pragma library\n"
    "// Generated by tools/aion2-tickets-import.py from the Clicktrough Inventory\n"
    "// plugin's data.js: the game's content tickets as SkeeveAN's Aion-DPS-Meter\n"
    "// (MIT, crates/aion2/data/characters/NOTICE-SkeeveAN.txt) read them from the\n"
    "// game client. id: [name, highest count, its second limit, server-wide,\n"
    "// a usage time, reset (\"d\" daily, \"w\" weekly, null)]. Do not edit by hand.\n"
    "var TICKETS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
)
(root / "qml" / "aion2" / "chartickets.js").write_text(js, encoding="utf-8")
shutil.copy(src / "NOTICE-SkeeveAN.txt", root / "crates" / "aion2" / "data" / "characters" / "NOTICE-SkeeveAN.txt")
print(len(out), "tickets")
