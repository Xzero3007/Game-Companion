#!/usr/bin/env python3
"""Takes Boss Callouts' data (A2 Tools' Enhanced Boss Telegraph, GPL-3.0,
taengu/A2Tools-Plugins plugins/boss-telegraph) into Game Companion's Boss
panel:

  qml/aion2/bossdata.js            the bosses, their lines, the checked mechanics
  crates/aion2/data/boss/watch.json  the skill and buff ids the capture passes on
  crates/aion2/data/boss/voice/    the built-in voice's clips (Kokoro, Apache 2.0)

Usage: tools/aion2-boss-import.py <A2Tools-Plugins checkout>
Run it again when its bosses.js or voice.js change.
"""
import base64, hashlib, json, os, sys

def load(path):
    s = open(path, encoding="utf-8").read()
    return json.loads(s[s.index("{"):s.rindex("}") + 1])

src = os.path.join(sys.argv[1], "plugins", "boss-telegraph")
repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = load(os.path.join(src, "bosses.js"))

out = os.path.join(repo, "qml", "aion2", "bossdata.js")
with open(out, "w", encoding="utf-8") as f:
    f.write(".pragma library\n// Generated by tools/aion2-boss-import.py from A2 Tools' Enhanced Boss\n"
            "// Telegraph (Boss Callouts) bosses.js, GPL-3.0, built by its author from the\n"
            "// game's tables. Do not edit by hand.\nvar D = ")
    json.dump(D, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

skills, buffs = set(), set()
for b in D["bosses"].values():
    skills.update(b.get("s", []))
for c in D["calls"]:
    (buffs if c["t"] == "abnormal" else skills).add(c["id"])
    if c.get("phase"):
        buffs.add(c["phase"]["a"])
data = os.path.join(repo, "crates", "aion2", "data", "boss")
os.makedirs(os.path.join(data, "voice"), exist_ok=True)
json.dump({"skills": sorted(skills), "buffs": sorted(buffs)}, open(os.path.join(data, "watch.json"), "w"), separators=(",", ":"))

V = load(os.path.join(src, "voice.js"))
index = {}
for text, clip in V.items():
    name = hashlib.sha1(text.encode("utf-8")).hexdigest()[:12] + ".ogg"
    open(os.path.join(data, "voice", name), "wb").write(base64.b64decode(clip))
    index[text] = name
json.dump(index, open(os.path.join(data, "voice", "index.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0, sort_keys=True)
print(f"{len(D['bosses'])} bosses, {len(D['calls'])} calls, {len(skills)} skills, {len(buffs)} buffs, {len(index)} clips")
