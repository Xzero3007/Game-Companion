#!/usr/bin/env python3
"""Takes the Map plugin over from the Clicktrough plugins (same author,
GPL-3.0): its tables and logic as one QML JavaScript library
(qml/aion2/mapkit.js), and its pictures (the game's map tiles and minimap
symbols) with their notices into crates/aion2/data/map/.

    tools/aion2-map-import.py <A2Tools-Clicktrough-Plugins>/plugins/map

The plugin's scripts are kept as they are; only `globalThis` becomes the
library's own object `G` (QML's global object is read only), and the few
newer forms QML's JavaScript (Qt 6.4) can't read are written the older way
(`lower`). render.js is taken for its helpers (detectMap, bearing ...); its
MapView, which needs a web page, is never called here: qml/MapView.qml
draws instead.
"""
import re
import shutil
import sys
from pathlib import Path


def lower(text):
    """`a ||= b`, `a ??= b` and object spread, written the older way. Only
    the forms the plugin uses; anything left over stops the import."""
    lhs = r"[A-Za-z_$][\w$]*(?:\.[\w$]+|\[[^\]]+\])*"
    # (x ||= y) inside parentheses; y without parentheses or with one call.
    text = re.sub(r"\((" + lhs + r") \|\|= ([^();]*(?:\([^()]*\))?)\)", r"(\1 || (\1 = \2))", text)
    # A statement: x ||= y; / x ??= y;
    text = re.sub(r"^(\s*)(" + lhs + r") \|\|= (.+);$", r"\1\2 = \2 || (\3);", text, flags=re.M)
    text = re.sub(r"^(\s*)(" + lhs + r") \?\?= (.+);$", r"\1if (\2 == null) \2 = \3;", text, flags=re.M)
    # const lk = (store[key] ||= {...}) has braces inside: by hand.
    text = text.replace("(store[key] ||= { g: {}, s: {}, c: [] })", "(store[key] || (store[key] = { g: {}, s: {}, c: [] }))")
    # Object spread.
    text = text.replace("{ ...data }", "Object.assign({}, data)")
    text = text.replace("{ ...e, rank }", "Object.assign({}, e, { rank })")
    text = text.replace("{ label, ...style(x, y), hit: !all, z: 50, focus }",
                        "Object.assign({ label }, style(x, y), { hit: !all, z: 50, focus })")
    left = [line for line in text.split("\n")
            if re.search(r"\|\|=|\?\?=|&&=|\{\s*\.\.\.|,\s*\.\.\.[A-Za-z_(][^\]]*\}", line)
            and not line.lstrip().startswith("//")]
    if left:
        sys.exit("not lowered:\n" + "\n".join(left[:10]))
    return text


src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
out_js = root / "qml" / "aion2" / "mapkit.js"
out_data = root / "crates" / "aion2" / "data" / "map"

parts = [
    ".pragma library\n",
    "// Generated by tools/aion2-map-import.py from the Clicktrough Map plugin\n",
    "// (data.js, areas.js, render.js, marks.js; GPL-3.0, see crates/aion2/data/map/\n",
    "// for the data's notices). Do not edit by hand.\n",
    "var G = {};\n",
    # Qt 6.4's JavaScript has no Array.prototype.flat / flatMap.
    "if (!Array.prototype.flat) Object.defineProperty(Array.prototype, 'flat', { value: function (d) {\n",
    "  d = d === undefined ? 1 : d;\n",
    "  return this.reduce(function (a, v) { return a.concat(Array.isArray(v) && d > 0 ? v.flat(d - 1) : [v]); }, []);\n",
    "}, writable: true, configurable: true });\n",
    "if (!Array.prototype.flatMap) Object.defineProperty(Array.prototype, 'flatMap', { value: function (f, t) {\n",
    "  return this.map(f, t).flat(1);\n",
    "}, writable: true, configurable: true });\n",
    "if (!Object.fromEntries) Object.defineProperty(Object, 'fromEntries', { value: function (it) {\n",
    "  var o = {}; for (var e of it) o[e[0]] = e[1]; return o;\n",
    "}, writable: true, configurable: true });\n",
]
for name in ["data.js", "areas.js", "render.js", "marks.js"]:
    text = (src / name).read_text(encoding="utf-8")
    parts.append(f"// ---- {name} ----\n")
    parts.append(text.replace("globalThis.", "G."))
    parts.append("\n")
parts.append("var D = G.MAP_DATA;\nvar K = G.MapKit;\nvar M = G.MapMarks;\n")
out_js.parent.mkdir(parents=True, exist_ok=True)
out_js.write_text(lower("".join(parts)), encoding="utf-8")

if out_data.exists():
    shutil.rmtree(out_data)
out_data.mkdir(parents=True)
shutil.copytree(src / "tiles", out_data / "tiles")
shutil.copytree(src / "icons", out_data / "icons")
for notice in sorted(src.glob("NOTICE-*.txt")):
    shutil.copy(notice, out_data / notice.name)
shutil.copy(src / "README.md", out_data / "README-plugin.md")
print(f"{out_js} ({out_js.stat().st_size // 1024} KB), {out_data}")
